function escapeHtml(text: string): string {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

// theme.{primaryColor,backgroundColor,textColor} go straight into a <style>
// block below with no other escaping — WebsiteContentSchema already
// enforces this hex format, but re-checking here means a row saved under an
// older, looser schema (or any future caller) can't break out of the CSS
// context, which was a stored-XSS vector reachable from the theme editor's
// free-text color input.
function sanitizeHexColor(value: string, fallback: string): string {
  return /^#[0-9a-fA-F]{3}([0-9a-fA-F]{3}){0,2}$/.test(value) ? value : fallback;
}

// The AI picks primaryColor freely (any hex, any lightness) — a hardcoded
// white button label would go invisible on a light accent color (e.g.
// pastel yellow), which is exactly the "white-on-white CTA" failure mode.
// Computing readable button text from the accent's actual luminance
// guarantees WCAG-safe contrast regardless of what the AI chose, for free
// (no extra tokens, applies to every generated page).
function readableTextColor(hex: string): "#ffffff" | "#0a0a0a" {
  const full = hex.length === 4 ? hex.slice(1).split("").map((c) => c + c).join("") : hex.slice(1, 7);
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(full.slice(i, i + 2), 16) / 255);
  const toLinear = (c: number) => (c <= 0.03928 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4));
  const luminance = 0.2126 * toLinear(r) + 0.7152 * toLinear(g) + 0.0722 * toLinear(b);
  return luminance > 0.55 ? "#0a0a0a" : "#ffffff";
}

/** Turns a YouTube/Vimeo watch/share URL into its embeddable iframe src — accepts whatever format a client pastes. */
function toEmbedUrl(url: string): string | null {
  try {
    const u = new URL(url);
    if (u.hostname.includes("youtu.be")) {
      return `https://www.youtube.com/embed/${u.pathname.slice(1)}`;
    }
    if (u.hostname.includes("youtube.com")) {
      const id = u.searchParams.get("v");
      if (id) return `https://www.youtube.com/embed/${id}`;
      if (u.pathname.startsWith("/embed/")) return url;
    }
    if (u.hostname.includes("vimeo.com")) {
      const id = u.pathname.split("/").filter(Boolean).pop();
      if (id) return `https://player.vimeo.com/video/${id}`;
    }
    return null;
  } catch {
    return null;
  }
}

function fontLink(fonts: string[]): string {
  const families = fonts.map((f) => `family=${encodeURIComponent(f)}:wght@400;600;700`).join("&");
  return `<link rel="preconnect" href="https://fonts.googleapis.com"><link rel="preconnect" href="https://fonts.gstatic.com" crossorigin><link href="https://fonts.googleapis.com/css2?${families}&display=swap" rel="stylesheet">`;
}


  // consultoría") — derived server-side from the business's industry, not
  // generated by the AI, so it costs nothing extra. heroImageUrl: this
  // business's own most-recently-uploaded photo (see AgentMedia), if any —
  // deliberately NOT a stock photo, so every client's page shows something
  // real and unique to them instead of the same generic photo repeated
  // across every business in an industry; the hero just renders text-only
